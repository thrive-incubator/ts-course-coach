export function exportModulePdf(
  proposal: Proposal,
  module: CourseModule,
  index: number
) {
  const co = proposal.course_overview;
  const courseEQ = proposal.design.essential_question;
  const features =
    module.interactive_features.length > 0
      ? module.interactive_features.map((f) => `<span class="pill">${escapeHtml(f)}</span>`).join('')
      : '<span class="empty">None selected.</span>';
  const materials =
    module.materials.length > 0
      ? '<ul>' +
        module.materials.map((m) => `<li>${escapeHtml(m.filename)}</li>`).join('') +
        '</ul>'
      : '<div class="empty">No materials uploaded.</div>';

  const body = `
    ${courseHeader(proposal)}
    <h2>Module ${index + 1} · ${escapeHtml(module.module_name || 'Untitled module')}</h2>
    <div class="kv">
      <div class="k">Contact hours</div><div class="v">${escapeHtml(module.contact_hours || '—')}</div>
      <div class="k">Format</div><div class="v">${escapeHtml(module.format || '—')}</div>
      <div class="k">Faculty</div><div class="v">${escapeHtml(module.faculty || '—')}</div>
    </div>
    ${courseEQ ? `<div class="field"><div class="field-label">Course essential question</div><div class="field-value">${escapeHtml(courseEQ)}</div></div>` : ''}
    ${field('Module essential question', module.essential_question)}
    <div class="field"><div class="field-label">Learning objectives (Bloom-tagged)</div>${objectivesList(module.objectives)}</div>
    ${field('Critical information', module.critical_information)}
    ${field('Opportunities for engagement', module.engagement_opportunities)}
    <div class="field"><div class="field-label">Interactive features</div><div>${features}</div></div>
    ${field('Interactive features — notes', module.interactive_features_notes)}
    ${field('Required readings', module.required_readings)}
    ${field('Recommended readings', module.recommended_readings)}
    ${field('Assignments', module.assignments)}
    <div class="field"><div class="field-label">Uploaded materials</div>${materials}</div>
  `;
  openPrintWindow({
    title: `${co.course_name || 'Course'} — Module ${index + 1}: ${module.module_name || 'Untitled'}`,
    bodyHtml: body,
  });
}
